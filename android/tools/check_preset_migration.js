'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const entry=index.match(/app-v\d+\.\d+\.\d+\.html/);
assert(entry,'Falta el punto de entrada HTML de la aplicación');
const html=fs.readFileSync(path.join(root,entry[0]),'utf8');
const decksSrc=fs.readFileSync(path.join(root,'presets/default-decks.js'),'utf8');
const base=JSON.parse(decksSrc.match(/POKER_BLITZ_DEFAULT_DECKS=(\[[\s\S]*?\]);/)[1]);
const begin=html.indexOf('function migrateDefaultDecks(');
const end=html.indexOf('function loadState()',begin);
assert(begin>=0&&end>begin,'Falta la migración de decks');
const migrate=new Function('defaultDecks',html.slice(begin,end)+'return migrateDefaultDecks;')(()=>base.map(d=>({...d})));
assert.equal(base.length,11,'Se esperan once decks predeterminados');
const old=base.filter(d=>!/Arkan|Regulus|Maverick/.test(d.name));
assert.equal(old.length,8);
const customized={...old[0],name:'Sibaris editado',cardIds:old[0].cardIds.slice(0,25)};
const userDeck={id:'usuario-1',name:'Mi propio deck',cardIds:[],hyperCardIds:[]};
const repaired=migrate([customized,...old.slice(1),userDeck],1);
assert.equal(repaired.length,12,'Deben mostrarse once presets y el deck personalizado');
for(const key of ['Arkan','Regulus','Maverick'])assert(repaired.some(d=>d.name.startsWith(key)),'Falta '+key);
assert.equal(repaired[0].name,'Sibaris editado','No sobrescribir edición de preset');
assert.equal(repaired[0].cardIds.length,25,'No alterar cartas de un deck editado');
assert(repaired.some(d=>d.id==='usuario-1'),'No borrar los decks del usuario');
assert.equal(new Set(repaired.map(d=>d.id)).size,repaired.length,'No duplicar decks');
assert.equal(migrate(repaired,2).length,repaired.length,'La migración solo debe ejecutarse una vez');
assert.equal(migrate(old,2).length,8,'Una eliminación posterior debe respetarse');
assert(html.includes('migrateDefaultDecks(existing,saved.defaultPresetVersion)'),'Migrar datos guardados');
assert(html.includes('migrateDefaultDecks(x.decks.map(d=>normalizeDeck(d)),x.defaultPresetVersion)'),'Migrar respaldos importados');
assert(html.includes('defaultPresetVersion:2'),'Registrar nueva versión de los presets');
assert(html.includes('Decks disponibles para elegir:'),'Mostrar contador de decks');
console.log('PASS: 8→11 presets, Arkan/Regulus/Maverick, edits, custom, no duplicates, import and persistence');
