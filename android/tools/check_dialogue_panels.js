'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const entry=fs.readFileSync(path.join(root,'index.html'),'utf8').match(/app-v\d+\.\d+\.\d+\.html/);
assert(entry,'Missing versioned entrypoint in index.html');
const html=fs.readFileSync(path.join(root,entry[0]),'utf8');
const presets=fs.readFileSync(path.join(root,'presets/default-decks.js'),'utf8');
const decks=JSON.parse(presets.match(/window\.POKER_BLITZ_DEFAULT_DECKS=(\[[\s\S]+\]);/)[1]);
const names=['Sibaris','Midas','Vórtice','Fortuna','Astra','Némesis','Arkan','Aceron','Regulus','Maverick'];
assert.equal(decks.length,10,'Expected ten character decks');
for(let i=0;i<10;i++)assert(decks[i].name.toLowerCase().includes(names[i].toLowerCase()),'Wrong dialogue order: '+names[i]);
const graphic=fs.readFileSync(path.join(root,'assets/poker_character_dialogues.webp'));
assert(graphic.length>30000,'Missing dialogue-panel artwork');
assert.equal(graphic.toString('ascii',0,4),'RIFF','Image must be a RIFF/WebP file');
assert.equal(graphic.toString('ascii',8,12),'WEBP','Wrong image format');
assert(html.includes('background-size:200% 500%'),'Missing 2-column 5-row dialogue atlas layout');
assert(html.includes('row:Math.floor(i/2)'),'Expected top-to-bottom dialogue mapping');
assert(html.includes('col:i%2'),'Expected left-to-right dialogue mapping');
assert(html.includes("i===5?'pink'"),'Némesis must be magenta');
assert(html.includes("i===7||i===8"),'Aceron and Regulus must be gold');
assert(html.includes("simCharacterHTML(d,sim.result||'')"),'Dialogue strip missing in gameplay');
assert(html.includes("characterDialogueHTML(deck,message,'battle')"),'Game character renderer must include dialogue image');
assert(html.includes("PRESET_DIALOGUE_PANELS[d.id]?"),'Dialogue preview missing in deck editor');
assert(html.includes("characterDialogueHTML(d,'','deck-row-dialogue')"),'Dialogue missing in deck list');
assert(html.includes("const picture=deck?.characterImage"),'Portrait must remain independent of dialogue');
console.log('PASS: 10 original dialogue panels integrated alongside original character portraits.');
